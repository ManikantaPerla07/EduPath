"""Learner-facing resource library for approved course materials.

Fulfills Phase D5 & Phase E requirements:
- Displays approved, published curriculum documents only.
- Groups by course topic with clear licensing and rights metadata.
- Includes external OpenStax reference reading link with explicit compliance notice.
- Prevents leakage of raw file bytes or administrative parameters.
"""

from collections import defaultdict
from typing import Any
import streamlit as st

from services.document_service import list_published_learning_resources
from ui.theme import render_page_header


def render_learning_resources(learner: dict[str, Any]) -> None:
    """Render the learner-facing library of approved educational resources."""
    render_page_header(
        "LEARNING RESOURCES",
        "Curriculum Library & Reference Materials",
        "Explore approved educational notes and reference readings that ground the EduPath AI Tutor.",
    )

    course_slug = "python-basics"

    try:
        resources = list_published_learning_resources(course_slug=course_slug)
    except Exception as exc:
        st.error(f"Unable to load learning resources at this time: {exc}")
        resources = []

    st.markdown(
        """
        <div class="edupath-dashboard-hero">
            <div class="eyebrow">VERIFIED KNOWLEDGE BASE</div>
            <h2>Grounding the AI Tutor with verified curriculum notes.</h2>
            <p>
                Every factual claim and code explanation generated by EduPath is cited
                directly from these approved educational resources.
            </p>
            <div class="edupath-hero-stats">
                <span class="edupath-hero-stat">11 Active Educational Resources</span>
                <span class="edupath-hero-stat">47 Embedded Vector Chunks</span>
                <span class="edupath-hero-stat">Original EduPath Authoring</span>
            </div>
        </div>
        """,
        unsafe_allow_html=True,
    )

    st.markdown("")

    # 1. Group resources by topic
    grouped_resources: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for res in resources:
        topic = res.get("topic_name") or "General Python"
        grouped_resources[topic].append(res)

    st.subheader("Approved Course Documents")
    st.caption("Active documents indexed into pgvector for grounded retrieval.")

    if grouped_resources:
        for topic_name, docs in sorted(grouped_resources.items()):
            with st.expander(f"📚 {topic_name} ({len(docs)} documents)", expanded=True):
                for doc in docs:
                    with st.container(border=True):
                        cols = st.columns([3, 1])
                        cols[0].markdown(f"**{doc['source_title']}**")
                        cols[0].caption(f"License: {doc['source_license']} · Rights: {doc['rights_basis']}")
                        cols[1].metric("Indexed Chunks", doc["chunk_count"])
    else:
        st.info("Loading published curriculum resources...")

    st.divider()

    # 2. External Reading Section: OpenStax
    st.subheader("External Reference Literature")
    st.caption("Supplementary open textbooks for self-directed study outside the AI Tutor.")

    with st.container(border=True):
        st.markdown("### OpenStax: Introduction to Python Programming")
        st.write(
            "An open-access, peer-reviewed textbook developed by Rice University covering "
            "Python programming fundamentals, algorithmic thinking, and basic computer science."
        )

        st.markdown(
            "> **Licensing & AI Compliance Notice:**\n"
            "> In accordance with Rice University's OpenStax AI terms of use, this textbook is provided "
            "> exclusively as an **external supplementary reading link**. It is **not ingested** into EduPath's "
            "> generative AI database or language models without prior written institutional permission. "
            "> All AI Tutor citations link exclusively to original EduPath curriculum notes."
        )

        st.link_button(
            "Open OpenStax Python Textbook (Official External Link)",
            "https://openstax.org/books/introduction-python-programming/pages/1-introduction",
            type="secondary",
        )
